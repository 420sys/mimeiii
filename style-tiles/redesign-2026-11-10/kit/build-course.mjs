/* Builds kit/course.js from the site's own course table (src/data/course.js),
   so every number in the prototypes is the real one.
   Run:  node style-tiles/redesign-2026-11-10/kit/build-course.mjs            */
import { readFileSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '../../../src/data/course.js');

// The site has no "type": "module", so node needs an .mjs copy to import it.
const tmp = join(mkdtempSync(join(tmpdir(), 'mimei-')), 'course.mjs');
writeFileSync(tmp, readFileSync(src, 'utf8'));
const { GROUPS, LESSONS, GOALS } = await import(pathToFileURL(tmp).href);

const ROMAN = ['I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII'];
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const plain = s => s.replace(/<[^>]+>/g, '');

const units = GROUPS.map((g, i) => {
  const lessons = LESSONS.filter(l => l.kind === 'lesson' && l.g === g.id).map(l => ({
    id: l.id,
    title: l.title,
    mins: l.mins,
    tag: l.tag,
    build: l.tag === 'build',
    checkpoints: (GOALS[l.id] || []).map(x => plain(x.t)),
  }));
  const cheat = LESSONS.find(l => l.kind === 'tool' && l.g === g.id);
  return {
    n: i + 1,
    roman: ROMAN[i],
    title: g.label,
    dir: `unit-${String(i + 1).padStart(2, '0')}-${slug(g.label)}`,
    lessons,
    mins: lessons.reduce((a, l) => a + l.mins, 0),
    cps: lessons.reduce((a, l) => a + l.checkpoints.length, 0),
    cheat: cheat ? { id: cheat.id, title: cheat.title } : null,
  };
});

const all = units.flatMap(u => u.lessons);
const totals = {
  units: units.length,
  lessons: all.length,
  checkpoints: all.reduce((a, l) => a + l.checkpoints.length, 0),
  minutes: all.reduce((a, l) => a + l.mins, 0),
};

/* The demo learner: units I and II finished, one checkpoint into 3.1. It is the
   state the crane stills use (DECISIONS 3.1 · CHECKPOINT 2/4 · RESUME 12 MIN). */
const done = ['1.0', '2.1', '2.2', '2.3', '2.4', '2.5', '2.6'];
const now = '3.1';
const reachedNow = 1;
const demo = {
  done,
  now,
  reachedNow,
  lessonsDone: done.length,
  checkpoints: all.filter(l => done.includes(l.id)).reduce((a, l) => a + l.checkpoints.length, 0) + reachedNow,
  tonight: { mins: 21, goal: 60 },
};

const out = `/* GENERATED by build-course.mjs from src/data/course.js. Do not edit by hand.
   ${totals.units} units, ${totals.lessons} lessons, ${totals.checkpoints} checkpoints, ${totals.minutes} minutes. */

export const UNITS = ${JSON.stringify(units, null, 1)};

export const TOTALS = ${JSON.stringify(totals)};

/* Demo progress, so the prototypes have something true-shaped to show.
   Nothing here is read from or written to the real store (ossuary-1). */
export const DEMO = ${JSON.stringify(demo)};

export const LESSONS = UNITS.flatMap(u => u.lessons.map(l => ({ ...l, unit: u.n })));
export const lessonById = id => LESSONS.find(l => l.id === id) || null;
export const unitOf = id => UNITS.find(u => u.lessons.some(l => l.id === id)) || null;
/** 'done' | 'now' | 'next' for a lesson id, from the demo progress. */
export const stateOf = id => (DEMO.done.includes(id) ? 'done' : id === DEMO.now ? 'now' : 'next');
/** Checkpoints reached in a lesson (all of them when done, the demo count when it is the current one). */
export const reachedIn = id => {
  const l = lessonById(id);
  return !l ? 0 : stateOf(id) === 'done' ? l.checkpoints.length : stateOf(id) === 'now' ? DEMO.reachedNow : 0;
};
`;
writeFileSync(join(here, 'course.js'), out);
console.log(JSON.stringify({ totals, demo: { ...demo, done: demo.done.length } }));
console.log(units.map(u => `${u.roman.padEnd(4)} ${u.title.padEnd(22)} ${u.lessons.length} lessons ${String(u.cps).padStart(2)} cps ${u.mins} min`).join('\n'));
